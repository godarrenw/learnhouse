def patch(path, tools, search):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    data.setdefault("tools", {})["assign"] = tools
    data.setdefault("search", {})["assign"] = search
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("patched", path)


